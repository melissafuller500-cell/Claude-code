'use strict';
// Tiny auto-escaping HTML templating. Every interpolated value is escaped
// unless it is the output of html`` or explicitly wrapped with raw().
class Raw {
  constructor(s) { this.s = String(s); }
  toString() { return this.s; }
}
const ESC = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };
const esc = (v) => String(v).replace(/[&<>"']/g, (c) => ESC[c]);
const raw = (s) => new Raw(s == null ? '' : s);

function renderValue(v) {
  if (v === null || v === undefined || v === false) return '';
  if (v instanceof Raw) return v.s;
  if (Array.isArray(v)) return v.map(renderValue).join('');
  return esc(v);
}

function html(strings, ...values) {
  let out = strings[0];
  for (let i = 0; i < values.length; i++) out += renderValue(values[i]) + strings[i + 1];
  return new Raw(out);
}

// JSON safe to embed inside <script type="application/json|ld+json">.
const json = (obj) => raw(JSON.stringify(obj).replace(/</g, '\\u003c').replace(/>/g, '\\u003e').replace(/&/g, '\\u0026').replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029'));

module.exports = { html, raw, esc, json, Raw };
